// Headless iPhone-size walkthrough: node tests/e2e.mjs [baseUrl]   (needs puppeteer-core + Chrome)
import puppeteer from "/workspace/pptr/node_modules/puppeteer-core/lib/esm/puppeteer/puppeteer-core.js";
const BASE = process.argv[2] || "http://localhost:8000";
const OUT = process.env.OUT || "/workspace/kitchen-os/shots";
const sleep = ms => new Promise(r => setTimeout(r, ms));
const b = await puppeteer.launch({ executablePath: "/usr/bin/google-chrome", headless: "new", args: ["--no-sandbox", "--hide-scrollbars"] });
const p = await b.newPage();
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await p.setUserAgent("Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 Version/17.0 Mobile/15E148 Safari/604.1");
p.on("pageerror", e => console.log("PAGE ERROR", e.message));
await p.goto(BASE, { waitUntil: "networkidle0" });
const click = async (sel) => { await p.waitForSelector(sel); await p.click(sel); await sleep(250); };
await p.screenshot({ path: `${OUT}/01-setup-who.png` });
await p.type('[data-n="0"]', "Mellow"); await click("#addm"); await p.type('[data-n="1"]', "Maya"); await click('[data-kid="1"]'); await p.screenshot({ path: `${OUT}/01b-setup-who.png` });
await click("#next1");
await click('[data-a="1|peanuts"]'); await click('[data-d="0|low sodium"]');
await p.screenshot({ path: `${OUT}/02-setup-allergies.png`, fullPage: false });
await click("#next2");
const inp = await p.$('input[data-k="fridge"]'); await inp.uploadFile("/workspace/kitchen-os/tests/fixtures/fridge.jpg"); await sleep(1200);
await click("#analyze");
await p.waitForSelector("#missgo", { timeout: 90000 });
await p.type("#miss", "we also have chicken thighs, pasta, heavy cream, parmesan, broccoli, rice and soy sauce"); await click("#missgo"); await sleep(1500);
await p.evaluate(() => window.scrollTo(0, 0));
await p.screenshot({ path: `${OUT}/03-setup-photos.png` });
await click("#next3"); await p.screenshot({ path: `${OUT}/04-setup-store.png` });
await click('[data-r="Instacart"]'); await click("#finish");
await p.waitForSelector("#cook", { timeout: 20000 }); await sleep(500);
await p.screenshot({ path: `${OUT}/05-tonight.png` });
await p.screenshot({ path: `${OUT}/05b-tonight-full.png`, fullPage: true });
await click("#exp"); await sleep(6000); await p.screenshot({ path: `${OUT}/06-explain.png`, fullPage: true });
await click('[data-tab="week"]'); await p.waitForSelector(".day"); await sleep(400); await p.screenshot({ path: `${OUT}/07-week.png` });
await click('[data-tab="shopping"]'); await p.waitForSelector(".item, .tiny"); await sleep(600); await p.screenshot({ path: `${OUT}/08-shopping.png`, fullPage: true });
await click('[data-tab="assistant"]'); await p.type("#msg", "we used all the yogurt"); await click("#send"); await sleep(1200);
await p.type("#msg", "use up chicken thighs"); await click("#send"); await sleep(1500);
await p.screenshot({ path: `${OUT}/09-assistant.png` });
console.log("manifest:", await p.evaluate(async () => (await fetch("/manifest.webmanifest")).status));
await b.close(); console.log("e2e done");
